def sb9600_crc(data: bytes) -> int:
    """Real SB9600 CRC byte, per Paul Banks's GM1200 analysis."""
    crc = 0
    for b in data:
        crc = SB9600_CRC_TABLE[(crc ^ b) & 0xFF]
    return crc


def sb9600_frame(payload: bytes) -> bytes:
    """Appends the real CRC byte, producing a complete classic-SB9600 frame."""
    return payload + bytes([sb9600_crc(payload)])


# Test vectors sniffed from a real GM1200 (from the original source's __main__
# block) -- verified at import time so a transcription error here is loud,
# not silent.
_TEST_VECTORS = [
    (bytes.fromhex("05600157"), 0x41),
    (bytes.fromhex("05600057"), 0x28),
    (bytes.fromhex("05690157"), 0x8F),
    (bytes.fromhex("00120506"), 0x39),
]
for _data, _expected in _TEST_VECTORS:
    _actual = sb9600_crc(_data)
    assert _actual == _expected, (
        f"sb9600_crc self-test failed for {_data.hex()}: "
        f"expected {_expected:02x}, got {_actual:02x}"
    )
del _data, _expected, _actual
