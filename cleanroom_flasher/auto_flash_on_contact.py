def sb9600_crc(data: bytes) -> int:
    crc = 0
    for b in data:
        crc = TABLE[(crc ^ b) & 0xFF]
    return crc

def run_auto_detector(port: str = "COM5", timeout_seconds: float = 60.0):
    print("=" * 65)
    print(f"[*] AUTO-FLASHER ACTIVE ON {port}")
    print("[*] Waiting for physical contact on XTS 2500 UDC port...")
    print("[*] (Clamp with rubber band/tape or hold connector tight against pads)")
    print("=" * 65)

    ser = serial.Serial(port, 19200, timeout=0.04)
    ser.dtr = True
    ser.rts = True
    
    start_time = time.time()
    last_print = 0
    contact_detected = False

    try:
        while time.time() - start_time < timeout_seconds:
            elapsed = int(time.time() - start_time)
            if elapsed != last_print and elapsed % 5 == 0:
                last_print = elapsed
                print(f"[*] Still listening... ({elapsed}s / {int(timeout_seconds)}s)")

            for baud in [19200, 9600, 38400]:
                ser.baudrate = baud
                
                # Test 1: Standard SB9600 ping
                raw4 = bytes([0x01, 0x00, 0x00, 0x14])
                pkt1 = raw4 + bytes([sb9600_crc(raw4)])
                ser.write(pkt1)
                ser.flush()
                time.sleep(0.015)
                rx1 = ser.read(50)
                if rx1:
                    print(f"\n[+] RADIO RESPONSE DETECTED! Baud: {baud}, Bytes: {rx1.hex()}")
                    contact_detected = True
                    break

                # Test 2: Standard Framed Ping
                pkt2 = bytes([0x05, 0x02, 0x14, 0x00, 0xE7])
                ser.write(pkt2)
                ser.flush()
                time.sleep(0.015)
                rx2 = ser.read(50)
                if rx2:
                    print(f"\n[+] RADIO RESPONSE DETECTED! Baud: {baud}, Bytes: {rx2.hex()}")
                    contact_detected = True
                    break

            if contact_detected:
                break
            time.sleep(0.03)

    finally:
        ser.close()

    if not contact_detected:
        print("\n[-] Auto-detector timed out without solid contact.")
        return False

    # Play success beep
    try:
        winsound.Beep(1500, 200)
        winsound.Beep(2000, 250)
    except Exception:
        pass

    print("[+] LATCHED ONTO RADIO! Proceeding with Backup and Flash...")
    return True

if __name__ == "__main__":
    port = sys.argv[1] if len(sys.argv) > 1 else "COM5"
    run_auto_detector(port)
